/** Translate one UI string, or return null when it is not a known UI string. */
export function translateText(text: string): string | null {
	const exact = RU[text];
	if (exact !== undefined) return exact;
	if (text.length > 160) return null;
	if (text.includes(" · ")) {
		const parts = text.split(" · ");
		let changed = false;
		const out = parts.map((part) => {
			const t = translateText(part);
			if (t !== null) { changed = true; return t; }
			return part;
		});
		return changed ? out.join(" · ") : null;
	}
	for (const [pattern, fn] of RU_RULES) {
		const match = pattern.exec(text);
		if (match) return fn(...match.slice(1));
	}
	return null;
}
